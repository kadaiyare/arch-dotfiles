import importlib.util
import json
from pathlib import Path
import shutil
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('theme_switch', Path(__file__).with_name('theme_switch.py'))
theme = importlib.util.module_from_spec(spec)
spec.loader.exec_module(theme)


class ConfigEditingTests(unittest.TestCase):
    def test_jsonc_preserves_unrelated_comments_nested_values_and_escapes(self):
        original = '''// top comment
{
  "theme": {"mode": "dark", /* nested */ "url": "https://example.com/[]"},
  // Keep my editor settings.
  "font": 23,
  "nested": [{"quoted": "a\\\"b"}],
}
'''
        result = theme.patch_jsonc(original, {'theme': {'mode': 'light'}, 'newKey': True})
        self.assertIn('// Keep my editor settings.', result)
        self.assertIn('"font": 23,', result)
        self.assertIn('"nested": [{"quoted": "a\\\"b"}],', result)
        self.assertIn('"theme": {"mode": "light"}', result)
        self.assertEqual(set(theme.jsonc_spans(result)[1]), {'theme', 'newKey', 'font', 'nested'})

    def test_jsonc_rejects_duplicate_keys(self):
        with self.assertRaises(ValueError): theme.patch_jsonc('{"theme":1,"theme":2}', {'theme': 3})

    def test_ini_preserves_fonts_comments_and_qt_byte_arrays(self):
        text = '# font comment\n[Appearance]\nstyle=kvantum\n\n[Fonts]\ngeneral="My Font,22"\ngeometry=@ByteArray(\\x0=stuff)'
        result = theme.patch_ini(text, 'Appearance', {'style': 'Fusion', 'custom_palette': 'true'})
        self.assertIn('[Fonts]\ngeneral="My Font,22"\ngeometry=@ByteArray(\\x0=stuff)', result)
        self.assertIn('# font comment', result)
        self.assertIn('style=Fusion\n', result)
        self.assertEqual(theme.patch_ini('[main]\nfont=Test', 'main', {'initial-color-theme': 'light'}), '[main]\nfont=Test\ninitial-color-theme=light\n')


class SwitchingTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(); self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.resources = Path(__file__).with_name('assets')
        self.config = self.home / '.config'; self.config.mkdir()
        for flavor in ['mocha', 'latte']:
            p = self.home / f'.local/share/themes/catppuccin-{flavor}-lavender-standard+default/gtk-3.0'
            p.mkdir(parents=True); (p / 'gtk.css').write_text('/* fixture theme */')
        self.write('nucleus-shell/config/configuration.json', json.dumps({'appearance': {'theme': 'dark', 'colors': {}}, 'secret': 'preserve-me', 'wallpapers': ['keep']}))
        self.write('qt6ct/qt6ct.conf', '[Fonts]\ngeneral="Original font,22"\n')
        self.write('foot/foot.ini', '[main]\nfont=Original:size=20\n')
        self.write('Code/User/settings.json', '{\n// keep\n"editor.fontSize": 21,\n"workbench.colorTheme":"Catppuccin Mocha",\n}')
        self.write('zed/settings.json', '{"theme":{"mode":"dark"},"custom":[1,2,3],}')

    def write(self, path, content):
        p = self.config / path; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(content)

    def test_roundtrip_preserves_user_settings_and_switches_all_palettes(self):
        switcher = theme.Switcher(self.home, self.resources)
        for mode, flavor, color in [('light', 'Latte', '#eff1f5'), ('dark', 'Mocha', '#1e1e2e')]:
            switcher.plan(mode); switcher.write(self.home / 'backup')
            state = json.loads((self.config / 'nucleus-shell/config/configuration.json').read_text())
            self.assertEqual(state['secret'], 'preserve-me'); self.assertEqual(state['wallpapers'], ['keep'])
            self.assertEqual(state['appearance']['theme'], mode)
            self.assertFalse(state['appearance']['colors']['autogenerated'])
            self.assertEqual(json.loads((self.config / 'nucleus-shell/config/colors.json').read_text())['background'], color)
            self.assertIn('Original font,22', (self.config / 'qt6ct/qt6ct.conf').read_text())
            self.assertIn('font=Original:size=20', (self.config / 'foot/foot.ini').read_text())
            self.assertIn('"Catppuccin ' + flavor + '"', (self.config / 'Code/User/settings.json').read_text())
            self.assertIn('"custom":[1,2,3]', (self.config / 'zed/settings.json').read_text())

    def test_gtk4_link_is_replaced_without_modifying_library_theme(self):
        original = self.home / 'library.css'; original.write_text('library unchanged')
        gtk = self.config / 'gtk-4.0'; gtk.mkdir(); (gtk / 'gtk.css').symlink_to(original)
        switcher = theme.Switcher(self.home, self.resources); switcher.plan('light'); switcher.write(self.home / 'backup')
        self.assertEqual(original.read_text(), 'library unchanged')
        self.assertFalse((gtk / 'gtk.css').is_symlink())
        self.assertIn('@media (prefers-color-scheme: dark)', (gtk / 'gtk.css').read_text())
        saved = json.loads((self.home / 'backup/files.json').read_text())
        self.assertEqual(saved[str(gtk / 'gtk.css')]['link'], str(original))

    def test_missing_asset_leaves_settings_untouched(self):
        switcher = theme.Switcher(self.home, self.resources)
        shutil.rmtree(self.home / '.local/share/themes')
        before = (self.config / 'qt6ct/qt6ct.conf').read_bytes()
        with self.assertRaises(FileNotFoundError): switcher.plan('light')
        self.assertEqual((self.config / 'qt6ct/qt6ct.conf').read_bytes(), before)

    def test_backend_state_wins_while_shell_file_is_waiting_to_save(self):
        state = self.home / '.local/state/catppuccin-theme'
        state.mkdir(parents=True)
        (state / 'current.json').write_text('{"mode":"light"}')
        self.assertEqual(theme.Switcher(self.home, self.resources).current(), 'light')

    def test_gtk3_removes_only_the_fixed_palette_override(self):
        self.write('gtk-3.0/gtk.css', '@import "colors.css";\n.custom { border-radius: 7px; }\n')
        self.write('gtk-3.0/settings.ini', '[Settings]\ngtk-modules=colorreload-gtk-module:example-module\n')
        switcher = theme.Switcher(self.home, self.resources)
        edits = switcher.plan('light')
        self.assertIn('.custom { border-radius: 7px; }', edits[self.config / 'gtk-3.0/gtk.css'])
        self.assertNotIn('@import "colors.css"', edits[self.config / 'gtk-3.0/gtk.css'])
        self.assertIn('gtk-modules=example-module', edits[self.config / 'gtk-3.0/settings.ini'])

    def test_firefox_setup_is_idempotent_and_preserves_other_preferences(self):
        root = self.home / '.mozilla/firefox'
        profile = root / 'example'; profile.mkdir(parents=True)
        (root / 'profiles.ini').write_text('[Profile0]\nPath=example\nIsRelative=1\n')
        (profile / 'user.js').write_text('user_pref("custom.preference", 42);\n')
        switcher = theme.Switcher(self.home, self.resources)
        for mode in ['light', 'dark']:
            switcher.plan(mode); switcher.write(self.home / 'backup')
        text = (profile / 'user.js').read_text()
        self.assertIn('user_pref("custom.preference", 42);', text)
        self.assertEqual(text.count('BEGIN CATPPUCCIN SYSTEM THEME'), 1)
        self.assertEqual((profile / 'chrome/userChrome.css').read_text().count('@import'), 1)

    def test_gtk4_stylesheet_parses(self):
        import gi
        gi.require_version('Gtk', '4.0')
        from gi.repository import Gtk
        provider = Gtk.CssProvider(); errors = []
        provider.connect('parsing-error', lambda obj, section, error: errors.append(str(error)))
        provider.load_from_string(theme.gtk4_css(json.loads((self.resources / 'palettes.json').read_text())))
        self.assertEqual(errors, [])


if __name__ == '__main__': unittest.main()
